#!/usr/bin/env python3
"""Generate the API route and management-command reference from the source.

The route table is read from the DRF router and the ``path()`` entries in
``src/api/v1/urls.py`` (Django is set up with ``config.settings_test``, so the
requirements must be installed). The command table is read with ``ast`` from
``src/*/management/commands/*.py`` — each command's ``help`` attribute and the
options its ``add_arguments`` declares — so no command module is imported.

Both files are generated, never edited by hand (UPS-DOC-05). Usage::

    python3 tools/gen_reference.py --write   # rewrite docs/reference/*.md
    python3 tools/gen_reference.py --check   # exit 1 when a file is stale

``tests/test_docs_reference.py`` runs the same comparison inside ``pytest``.
"""

from __future__ import annotations

import argparse
import ast
import inspect
import os
import re
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
ROUTES_DOC = Path("docs/reference/api-routes.md")
COMMANDS_DOC = Path("docs/reference/management-commands.md")
COMMAND = "python3 tools/gen_reference.py --write"
METHOD_ORDER = ["get", "post", "put", "patch", "delete"]


def _header(title: str, summary: str) -> list[str]:
    return [
        f"<!-- GENERATED by `{COMMAND}` — do not edit by hand -->",
        f"# {title}",
        "",
        f"> {summary}",
        "",
    ]


def _cell(text: str) -> str:
    """One Markdown table cell: whitespace collapsed, RST literals as code, `<`/`>` and pipes escaped."""
    text = re.sub(r"``([^`]+)``", r"`\1`", " ".join(text.split()))
    parts = re.split(r"(`[^`]*`)", text)
    text = "".join(
        p if p.startswith("`") else p.replace("<", "&lt;").replace(">", "&gt;") for p in parts
    )
    return text.replace("|", "\\|") or "—"


def _summary(obj) -> str:
    """First paragraph of an object's *own* docstring, for code that lives in ``src/``.

    A third-party view (DRF, drf-spectacular) is named by its package instead, so a
    dependency upgrade that rewords a docstring cannot make this reference stale.
    """
    package = (getattr(obj, "__module__", "") or "").split(".")[0]
    if not (SRC / package).is_dir():
        return f"Provided by `{package}`."
    doc = obj.__dict__.get("__doc__") if isinstance(obj, type) else getattr(obj, "__doc__", None)
    if not doc:
        return ""
    return inspect.cleandoc(doc).split("\n\n")[0]


def _codes(items) -> str:
    return ", ".join(f"`{i}`" for i in items) or "—"


# --------------------------------------------------------------------------- routes


def _setup_django() -> None:
    if str(SRC) not in sys.path:
        sys.path.insert(0, str(SRC))
    os.environ.setdefault("DJANGO_SETTINGS_MODULE", "config.settings_test")
    import django

    django.setup()


def _mounts() -> tuple[list[str], list[str]]:
    """Where the root URLconf includes ``api.v1.urls`` directly, and where it aliases it."""
    from django.conf import settings
    from django.urls import URLResolver, get_resolver

    canonical, aliases = [], []
    for entry in get_resolver(settings.ROOT_URLCONF).url_patterns:
        if not isinstance(entry, URLResolver):
            continue
        name = getattr(entry.urlconf_module, "__name__", "")
        prefix = "/" + str(entry.pattern)
        if name == "api.v1.urls":
            canonical.append(prefix)
        elif name == "api.urls":
            aliases.append(prefix)
    return canonical, aliases


def _path(base: str, pattern: str) -> str:
    return base + re.sub(r"<(?:\w+:)?(\w+)>", r"{\1}", pattern)


def _access(classes) -> str:
    return ", ".join(f"`{c.__name__}`" for c in classes) or "public"


def _filters(viewset) -> list[str]:
    if getattr(viewset, "filterset_fields", None):
        return list(viewset.filterset_fields)
    filterset = getattr(viewset, "filterset_class", None)
    return list(filterset.base_filters) if filterset is not None else []


_MODULE_FUNCS: dict[str, dict[str, ast.FunctionDef]] = {}


def _params(func) -> str:
    """Query parameters and body fields a handler reads, found with ``ast``.

    Catches ``request.query_params.get("x")`` / ``.getlist("x")`` (also through a
    local alias such as ``qp = request.query_params``) and ``request.data.get("x")``,
    and follows calls to module-level helpers in the same file (``_wants_async``).
    """
    module = inspect.getmodule(func)
    if module is None or not (SRC / module.__name__.split(".")[0]).is_dir():
        return ""
    if module.__name__ not in _MODULE_FUNCS:
        tree = ast.parse(inspect.getsource(module))
        _MODULE_FUNCS[module.__name__] = {
            n.name: n for n in tree.body if isinstance(n, ast.FunctionDef)
        }
    helpers = _MODULE_FUNCS[module.__name__]
    query: list[str] = []
    body: list[str] = []

    def visit(node: ast.AST, seen: set[str]) -> None:
        aliases = {
            t.id
            for n in ast.walk(node)
            if isinstance(n, ast.Assign)
            and isinstance(n.value, ast.Attribute)
            and n.value.attr == "query_params"
            for t in n.targets
            if isinstance(t, ast.Name)
        }
        calls = sorted(
            (n for n in ast.walk(node) if isinstance(n, ast.Call)),
            key=lambda n: (n.lineno, n.col_offset),
        )
        for n in calls:  # source order, so the columns read like the handler
            if isinstance(n.func, ast.Name) and n.func.id in helpers and n.func.id not in seen:
                seen.add(n.func.id)
                visit(helpers[n.func.id], seen)
                continue
            if not (isinstance(n.func, ast.Attribute) and n.func.attr in ("get", "getlist")):
                continue
            if not (
                n.args and isinstance(n.args[0], ast.Constant) and isinstance(n.args[0].value, str)
            ):
                continue
            owner, name = n.func.value, n.args[0].value
            if (isinstance(owner, ast.Attribute) and owner.attr == "query_params") or (
                isinstance(owner, ast.Name) and owner.id in aliases
            ):
                query.append(name)
            elif isinstance(owner, ast.Attribute) and owner.attr == "data":
                body.append(name)

    visit(ast.parse(textwrap.dedent(inspect.getsource(func))), set())
    parts = []
    if query:
        parts.append("query " + _codes(dict.fromkeys(query)))
    if body:
        parts.append("body " + _codes(dict.fromkeys(body)))
    return "; ".join(parts)


def _route_path(route, prefix: str, lookup: str) -> str:
    url = route.url.lstrip("^").rstrip("$")
    for key, value in (("{prefix}", prefix), ("{lookup}", lookup), ("{trailing_slash}", "/")):
        url = url.replace(key, value)
    return url


def render_routes() -> str:
    _setup_django()
    from api.v1 import urls

    canonical, aliases = _mounts()
    base = canonical[0]
    router = urls.router
    alias_note = (
        f" The root URLconf also mounts the same URLconf at {_codes(aliases)} as a legacy alias."
        if aliases
        else ""
    )
    lines = _header(
        "API routes",
        "Every REST route the versioned API serves — method, path, view, access rule, parameters "
        "and summary — read from the DRF router and `src/api/v1/urls.py`.",
    )
    lines += [
        f"Paths are relative to the API host. The canonical base is `{base}`.{alias_note} "
        "The router also accepts a format suffix (for example `.json`) on each route; those "
        "variants are not listed. `Access` names the permission classes DRF applies (`public`: "
        "none). `Params` lists the query parameters and body fields the handler itself reads; "
        "list routes also take the filters and search fields in **Resources**.",
        "",
        "## Resources",
        "",
        "| Prefix | ViewSet | Lookup | Filters | Search | Summary |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for prefix, viewset, _basename in router.registry:
        lookup = viewset.lookup_url_kwarg or viewset.lookup_field
        lines.append(
            f"| `{base}{prefix}/` | `{viewset.__name__}` | `{lookup}` "
            f"| {_codes(_filters(viewset))} | {_codes(getattr(viewset, 'search_fields', None) or [])} "
            f"| {_cell(_summary(viewset))} |"
        )

    lines += [
        "",
        "## Routes",
        "",
        "| Method | Path | View | Access | Params | Summary |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for pattern in urls.urlpatterns:
        view = getattr(getattr(pattern, "callback", None), "view_class", None)
        if view is None:
            continue
        methods = [m for m in METHOD_ORDER if hasattr(view, m)]
        params = "; ".join(p for p in (_params(getattr(view, m)) for m in methods) if p)
        lines.append(
            f"| {' '.join(m.upper() for m in methods)} | `{_path(base, str(pattern.pattern))}` "
            f"| `{view.__name__}` | {_access(view.permission_classes)} | {_cell(params)} "
            f"| {_cell(_summary(view))} |"
        )
    if router.include_root_view:
        lines.append(
            f"| GET | `{base}` | `APIRootView` | public | — | The router's browsable index of the "
            f"resources above (`{type(router).__name__}`). |"
        )
    for prefix, viewset, _basename in router.registry:
        lookup = "{" + (viewset.lookup_url_kwarg or viewset.lookup_field) + "}"
        for route in router.get_routes(viewset):
            mapping = router.get_method_map(viewset, route.mapping)
            if not mapping:
                continue
            actions = list(dict.fromkeys(mapping[m] for m in METHOD_ORDER if m in mapping))
            extra = [h for h in (getattr(viewset, a) for a in actions) if hasattr(h, "mapping")]
            handler = extra[0] if extra else None
            perms = viewset.permission_classes
            if handler is not None:
                perms = handler.kwargs.get("permission_classes", perms)
            lines.append(
                f"| {' '.join(m.upper() for m in METHOD_ORDER if m in mapping)} "
                f"| `{base}{_route_path(route, prefix, lookup)}` "
                f"| `{viewset.__name__}.{'/'.join(actions)}` | {_access(perms)} "
                f"| {_cell(_params(handler) if handler else '')} "
                f"| {_cell(_summary(handler) if handler else '')} |"
            )
    return "\n".join(lines) + "\n"


# --------------------------------------------------------------------------- commands


def _module_functions(tree: ast.Module) -> dict[str, ast.FunctionDef]:
    return {n.name: n for n in tree.body if isinstance(n, ast.FunctionDef)}


def _relative_imports(tree: ast.Module, here: Path) -> dict[str, Path]:
    """Names imported from sibling modules (``from ._base import f``) mapped to their file."""
    found = {}
    for node in tree.body:
        if isinstance(node, ast.ImportFrom) and node.level == 1 and node.module:
            for alias in node.names:
                found[alias.asname or alias.name] = here / f"{node.module}.py"
    return found


def _options(func: ast.FunctionDef, local: dict, imported: dict, seen: set) -> list[str]:
    """Flags declared by ``*.add_argument(...)`` in ``func``, following helper calls."""
    flags: list[str] = []
    for node in ast.walk(func):
        if not isinstance(node, ast.Call):
            continue
        if isinstance(node.func, ast.Attribute) and node.func.attr == "add_argument":
            names = [
                a.value
                for a in node.args
                if isinstance(a, ast.Constant) and isinstance(a.value, str)
            ]
            if not names:
                continue
            flag = max(names, key=len) if names[0].startswith("-") else f"<{names[0]}>"
            required = any(
                k.arg == "required" and isinstance(k.value, ast.Constant) and k.value.value is True
                for k in node.keywords
            )
            flags.append(f"{flag} (required)" if required else flag)
        elif isinstance(node.func, ast.Name) and node.func.id not in seen:
            seen.add(node.func.id)
            if node.func.id in local:
                flags += _options(local[node.func.id], local, imported, seen)
            elif node.func.id in imported and imported[node.func.id].is_file():
                other = ast.parse(imported[node.func.id].read_text(encoding="utf-8"))
                target = _module_functions(other).get(node.func.id)
                if target is not None:
                    flags += _options(target, _module_functions(other), imported, seen)
    return flags


def _command(path: Path) -> tuple[str, list[str]]:
    tree = ast.parse(path.read_text(encoding="utf-8"))
    help_text, flags = "", []
    for node in tree.body:
        if not (isinstance(node, ast.ClassDef) and node.name == "Command"):
            continue
        for item in node.body:
            if isinstance(item, ast.Assign) and any(
                isinstance(t, ast.Name) and t.id == "help" for t in item.targets
            ):
                help_text = ast.literal_eval(item.value)
            if isinstance(item, ast.FunctionDef) and item.name == "add_arguments":
                flags = _options(
                    item, _module_functions(tree), _relative_imports(tree, path.parent), set()
                )
    return help_text, flags


def render_commands() -> str:
    lines = _header(
        "Management commands",
        "Every `manage.py` command the Django apps ship, grouped by app, with its help text and options — read from `src/*/management/commands/*.py`.",
    )
    lines += [
        "Run them from `src/`: `cd src && python manage.py <command> [options]`. "
        "`python manage.py help <command>` prints the full argument help, including defaults.",
        "",
    ]
    for app_dir in sorted(p for p in SRC.iterdir() if (p / "management" / "commands").is_dir()):
        files = sorted(
            f
            for f in (app_dir / "management" / "commands").glob("*.py")
            if not f.name.startswith("_")
        )
        if not files:
            continue
        lines += [
            f"## `{app_dir.name}`",
            "",
            "| Command | Purpose | Options |",
            "| --- | --- | --- |",
        ]
        for f in files:
            help_text, flags = _command(f)
            lines.append(
                f"| `{f.stem}` | {_cell(help_text)} | {_cell(', '.join(f'`{x}`' for x in flags))} |"
            )
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


# --------------------------------------------------------------------------- main


def outputs() -> dict[Path, str]:
    return {COMMANDS_DOC: render_commands(), ROUTES_DOC: render_routes()}


def stale(root: Path = ROOT) -> list[Path]:
    """The generated files whose committed content differs from a fresh render."""
    out = []
    for rel, text in outputs().items():
        target = root / rel
        if not target.is_file() or target.read_text(encoding="utf-8") != text:
            out.append(rel)
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="rewrite the generated files")
    mode.add_argument("--check", action="store_true", help="exit 1 when a generated file is stale")
    args = parser.parse_args(argv)
    if args.check:
        bad = stale()
        for rel in bad:
            print(f"stale: {rel} — run {COMMAND}", file=sys.stderr)
        return 1 if bad else 0
    for rel, text in outputs().items():
        (ROOT / rel).parent.mkdir(parents=True, exist_ok=True)
        (ROOT / rel).write_text(text, encoding="utf-8")
        print(f"wrote {rel}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
